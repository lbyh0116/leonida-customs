using System.Globalization;
using System.Text.RegularExpressions;

namespace VehicleStudio;

internal static class UiText
{
    public static bool English { get; set; }

    public static string T(string value) => English ? Translations.GetValueOrDefault(value, value) : value;

    public static string F(string template, params object?[] args) =>
        string.Format(English ? CultureInfo.GetCultureInfo("en-US") : CultureInfo.GetCultureInfo("zh-CN"), T(template), args);

    public static string Diagnostic(string value)
    {
        if (!English)
            return value;
        if (Translations.TryGetValue(value, out var translated))
            return translated;
        value = value.Replace("缺少 ", "Missing ", StringComparison.Ordinal)
            .Replace("无法读取 ", "Cannot read ", StringComparison.Ordinal)
            .Replace("Xbox RPF9 档案头不匹配 ", "Invalid Xbox RPF9 header: ", StringComparison.Ordinal)
            .Replace("；", "; ", StringComparison.Ordinal).Replace("、", ", ", StringComparison.Ordinal)
            .Replace(" · 恢复名称", " · Resolving names", StringComparison.Ordinal)
            .Replace(" · 扫描档案", " · Scanning archives", StringComparison.Ordinal);
        value = Regex.Replace(value, "^正在读取 (.+) 的基础模型$", "Reading the $1 base model");
        value = Regex.Replace(value, "^Godot 无法读取整车 GLB（(.+)）。$", "Godot could not read the vehicle GLB ($1).");
        value = Regex.Replace(value, "^SixNG 未返回有效结果（退出码 (.+)）。$", "SixNG did not return a valid result (exit code $1).");
        return Regex.Replace(value, "^当前解码器无法单独预览这个车轴的 (.+)，该选项未应用。$", "The decoder cannot fit $1 separately on this axle. The selection was skipped.");
    }

